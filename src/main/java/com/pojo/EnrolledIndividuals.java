package com.pojo;



public class EnrolledIndividuals {

    private String userId;
    private String name;

    public EnrolledIndividuals() {}

    public String getUserId() {
        return userId;
    }

    public void setUserId(String userId) {
        this.userId = userId;
    }

    public String getName() {
        return name;
    }

    public void setName(String name) {
        this.name = name;
    }
}


